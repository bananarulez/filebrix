"""Generates PDF fixtures that do NOT share a generator with the code under test.

Every pre-existing PDF fixture came from pdf-lib or pypdf — the same libraries
the PDF engine uses to read them — so the suite could only ever prove the
engine round-trips its own output. Real files carry structure synthetic ones
don't: cross-reference streams, object streams, linearization, producer-specific
object layout, and fonts that are referenced but not embedded.

Producers used here, both deliberately unrelated to pdf-lib:
  * reportlab (BSD licence) — a mature, independent PDF writer.
  * qpdf, via pikepdf (Apache-2.0 / MPL-2.0) — for linearization and for
    rewriting into PDF 1.5 object/xref streams.

Neither is an npm dependency; both are fixture-generation tooling only, the
same arrangement as the existing Pillow/pypdf scripts beside this one.

Run manually whenever fixtures need regenerating:

    python -m pip install reportlab pikepdf
    python scripts/generate-real-world-pdf-fixtures.py
"""
import io
import os
import random

import pikepdf
from PIL import Image, ImageDraw, ImageFilter
from reportlab.lib.pagesizes import LETTER
from reportlab.lib.utils import ImageReader
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.cidfonts import UnicodeCIDFont
from reportlab.pdfgen import canvas

FIXTURES_DIR = os.path.join(os.path.dirname(__file__), "..", "tests", "fixtures", "pdf")
os.makedirs(FIXTURES_DIR, exist_ok=True)

# Deterministic output: the "scanned" page uses randomness for speckle, and a
# fixture that changes bytes on every run would churn the repo pointlessly.
random.seed(20260730)


def path(name):
    return os.path.join(FIXTURES_DIR, name)


def report(name):
    print(f"wrote {name} ({os.path.getsize(path(name)):,} bytes)")


# --- real-reportlab.pdf: ordinary multi-page text document ------------------
# The baseline "made by something else" file: normal text, standard Type1
# base-14 fonts, reportlab's own object layout and Producer string.
c = canvas.Canvas(path("real-reportlab.pdf"), pagesize=LETTER)
c.setTitle("FileBrix real-producer fixture")
c.setAuthor("scripts/generate-real-world-pdf-fixtures.py")
for page_number in range(1, 4):
    c.setFont("Helvetica-Bold", 20)
    c.drawString(72, 720, f"Real-producer fixture — page {page_number}")
    c.setFont("Times-Roman", 12)
    c.drawString(72, 690, "Generated by reportlab, not pdf-lib.")
    c.drawString(72, 670, "Exercises a producer the PDF engine has never round-tripped.")
    c.showPage()
c.save()
report("real-reportlab.pdf")


# --- real-cjk-noembed.pdf: CJK text in a NON-EMBEDDED standard Asian font ---
# This is the one that exercises pdf.js's self-hosted cmaps/ and
# standard_fonts/ (scripts/copy-pdfjs-assets.mjs). HeiseiMin-W3 is an Adobe
# standard Asian face: the PDF references it and supplies CID metrics, but
# embeds no font program, so a viewer must resolve the CMap itself. Missing
# cmaps degrade silently — wrong glyphs or none — rather than erroring, which
# is exactly why this needed a fixture rather than a code review.
pdfmetrics.registerFont(UnicodeCIDFont("HeiseiMin-W3"))
c = canvas.Canvas(path("real-cjk-noembed.pdf"), pagesize=LETTER)
c.setTitle("CJK, non-embedded standard font")
c.setFont("HeiseiMin-W3", 24)
c.drawString(72, 700, "日本語のテキストサンプル")
c.setFont("HeiseiMin-W3", 16)
c.drawString(72, 660, "これは埋め込みフォントではありません。")
c.setFont("Helvetica", 12)
c.drawString(72, 620, "ASCII alongside CJK, so text extraction has both to handle.")
c.showPage()
c.save()
report("real-cjk-noembed.pdf")


# --- real-scanned-image-only.pdf: a scanner-style, text-free page ----------
# One full-page JPEG and no text operators at all — what a document scanner
# or a photographed page produces. Text extraction should yield (almost)
# nothing here; that is the correct result, not a failure.
page_w, page_h = 1240, 1600  # ~150 dpi letter
scan = Image.new("RGB", (page_w, page_h), (252, 250, 245))
draw = ImageDraw.Draw(scan)
for row in range(14):
    y = 180 + row * 90
    width = random.randint(500, 980)
    draw.rectangle((150, y, 150 + width, y + 26), fill=(35, 33, 38))
# Speckle + blur: scanner noise, and it stops the JPEG compressing to nothing.
for _ in range(9000):
    x, y = random.randint(0, page_w - 1), random.randint(0, page_h - 1)
    v = random.randint(150, 235)
    scan.putpixel((x, y), (v, v, v))
scan = scan.filter(ImageFilter.GaussianBlur(0.6))

scan_buffer = io.BytesIO()
scan.save(scan_buffer, format="JPEG", quality=70)
scan_buffer.seek(0)

c = canvas.Canvas(path("real-scanned-image-only.pdf"), pagesize=LETTER)
c.setTitle("Scanner-style image-only page")
c.drawImage(ImageReader(scan_buffer), 0, 0, width=LETTER[0], height=LETTER[1])
c.showPage()
c.save()
report("real-scanned-image-only.pdf")


# --- real-linearized.pdf: web-optimized (linearized) layout -----------------
# qpdf rewrites the file with the first page's objects up front and a
# linearization parameter dictionary — the "fast web view" layout a browser
# can render before the whole file arrives. pdf-lib never emits this.
with pikepdf.open(path("real-reportlab.pdf")) as pdf:
    pdf.save(path("real-linearized.pdf"), linearize=True)
report("real-linearized.pdf")


# --- real-objstm.pdf: PDF 1.5 object streams + cross-reference stream -------
# Most objects packed into compressed object streams, with a binary xref
# stream instead of a classic xref table. A parser that only handles the
# classic table cannot read this at all.
with pikepdf.open(path("real-reportlab.pdf")) as pdf:
    pdf.save(
        path("real-objstm.pdf"),
        object_stream_mode=pikepdf.ObjectStreamMode.generate,
        compress_streams=True,
    )
report("real-objstm.pdf")

print("\nAll real-producer PDF fixtures written.")
