import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import path from "node:path";
import ignore from "ignore";
import { describe, expect, it } from "vitest";
import { CLOUDFLARE_MAX_ASSET_BYTES, R2_BACKED_ENGINE_ASSETS } from "@/lib/engineAssets";

const ROOT = path.resolve(__dirname, "..", "..");
const PUBLIC_DIR = path.join(ROOT, "public");

/**
 * Cloudflare rejects a deploy outright if any single static asset exceeds
 * 25 MiB. Three things have to agree on which files those are — their size on
 * disk, `public/.assetsignore`, and the allow-list in
 * `app/duckdb/[file]/route.ts` — and nothing else connects them.
 *
 * The failure this guards against isn't subtle, but it is late and remote: a
 * `@duckdb/duckdb-wasm` bump (or a new engine with a big binary) would pass
 * `tsc`, lint, every other test and `npm run build`, then be rejected by
 * `wrangler deploy` on someone else's machine.
 *
 * `public/` is generated by the postinstall copy scripts and gitignored, so
 * these tests skip rather than fail when it hasn't been generated yet.
 */

/**
 * Wrangler always excludes these three itself, whatever `.assetsignore` says —
 * they configure the asset handler rather than being served by it. They'd
 * otherwise show up as "excluded but would have fit".
 */
const WRANGLER_METAFILES = new Set([".assetsignore", "_headers", "_redirects"]);

/** Every file under `public/`, as a path relative to it, unix-separated. */
function publicFiles(dir = PUBLIC_DIR, prefix = ""): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) return publicFiles(path.join(dir, entry.name), relative);
    return [relative];
  });
}

/**
 * Mirrors `createAssetsIgnoreFunction` in wrangler's own source: the same
 * `ignore` package, the same three implicit metafile patterns, then the
 * contents of `.assetsignore`.
 */
function assetIgnoreMatcher(): (relativePath: string) => boolean {
  const contents = readFileSync(path.join(PUBLIC_DIR, ".assetsignore"), "utf8");
  const matcher = ignore().add([
    "/.assetsignore",
    "/_redirects",
    "/_headers",
    ...contents.split("\n"),
  ]);
  return (relativePath) => matcher.ignores(relativePath);
}

describe("Cloudflare static-asset size limit", () => {
  const generated = existsSync(path.join(PUBLIC_DIR, "duckdb"));

  it.skipIf(!generated)("every file over the 25 MiB limit is excluded from the upload", () => {
    const isIgnored = assetIgnoreMatcher();

    const oversized = publicFiles().filter(
      (relative) => statSync(path.join(PUBLIC_DIR, relative)).size > CLOUDFLARE_MAX_ASSET_BYTES
    );

    // Not an assertion about *which* files — a new oversized asset is allowed
    // to appear, it just has to be handled rather than silently break a deploy.
    for (const relative of oversized) {
      expect(isIgnored(relative), `${relative} is over 25 MiB but would still be uploaded`).toBe(
        true
      );
    }
  });

  it.skipIf(!generated)("excludes nothing that would have fit", () => {
    // The inverse mistake: an over-broad pattern (`duckdb/*`) silently drops
    // the two ~800 KB worker scripts, and DuckDB then fails to start with no
    // clue as to why.
    const isIgnored = assetIgnoreMatcher();

    for (const relative of publicFiles()) {
      if (WRANGLER_METAFILES.has(relative)) continue;
      if (statSync(path.join(PUBLIC_DIR, relative)).size > CLOUDFLARE_MAX_ASSET_BYTES) continue;
      expect(isIgnored(relative), `${relative} fits the limit but is excluded`).toBe(false);
    }
  });

  it.skipIf(!generated)("serves every excluded file back from R2", () => {
    // An excluded file that no route serves is simply a 404 in production.
    const isIgnored = assetIgnoreMatcher();
    const excluded = publicFiles().filter(
      (relative) => !WRANGLER_METAFILES.has(relative) && isIgnored(relative)
    );

    expect(excluded.sort()).toEqual(
      R2_BACKED_ENGINE_ASSETS.map((name) => `duckdb/${name}`).sort()
    );
  });
});
