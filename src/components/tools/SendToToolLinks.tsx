"use client";

import Link from "next/link";
import { getToolsAcceptingFormat, getToolUrl } from "@/registry";
import type { ToolDefinition } from "@/registry/types";
import { categorizeActions, hasAnyActions, type CategorizedActions } from "@/lib/detect/categorizeActions";
import { EXTENSION_MAP, extensionOf } from "@/lib/detect/signatures";
import { setPendingFile } from "@/lib/fileHandoff";
import { sanitizeFilename } from "@/lib/security/filenames";

const SECTION_LABELS: Record<keyof CategorizedActions, string> = {
  view: "View",
  convert: "Convert",
  edit: "Edit",
  utility: "Tools",
};

interface SendToToolLinksProps {
  /** The result's filename, used both to identify its format and as the handed-off File's name. */
  filename: string;
  /** The result itself, still in memory — never uploaded, never written to storage. */
  blob: Blob;
  /** The tool producing this result, so it doesn't offer to send the output straight back to itself. */
  excludeToolSlug?: string;
}

/**
 * "Send to another tool" — chains a tool's *output* into the next tool
 * without a download/re-drop round trip, reusing the same handoff the
 * homepage's Universal File Drop uses (`lib/fileHandoff.ts`, CLAUDE.md rule
 * 9): a module-scoped, single-use, slug-scoped, 60s-expiry live `File`
 * reference that survives Next's client-side route transition. No storage
 * API, no serialization, no network — a hard reload of the destination
 * legitimately gets `null` back and shows its normal empty drop zone.
 *
 * The offered tools come from `getToolsAcceptingFormat()` grouped by
 * `categorizeActions()` — the exact pair `UniversalFileDrop` uses — so this
 * can never advertise a tool that doesn't exist or one that doesn't accept
 * the format.
 *
 * The output's format is derived from its filename extension rather than by
 * sniffing bytes: the filename is generated by the tool that just produced
 * the result (`converted.jpg`, `merged.pdf`), so the extension is
 * authoritative here in a way it isn't for a user-supplied file — and it
 * keeps this synchronous, so no spinner appears next to a Download button.
 */
export function SendToToolLinks({ filename, blob, excludeToolSlug }: SendToToolLinksProps) {
  const extension = extensionOf(filename);
  const format = extension ? EXTENSION_MAP[extension] : undefined;
  if (!format) return null;

  const candidates = getToolsAcceptingFormat(format).filter((tool) => tool.slug !== excludeToolSlug);
  const actions = categorizeActions(candidates);
  if (!hasAnyActions(actions)) return null;

  // A File, not the raw Blob: the destination's drop zone works with File
  // (it reads .name), and the name must be sanitized before it travels any
  // further — rule 7 treats a filename as untrusted input wherever it can
  // become a download name or an archive entry name downstream.
  function handOff(tool: ToolDefinition) {
    const safeName = sanitizeFilename(filename);
    setPendingFile(tool.slug, new File([blob], safeName, { type: blob.type }));
  }

  return (
    <section
      aria-label="Send this result to another tool"
      className="flex flex-col gap-2 rounded-lg border border-gray-200 p-3 dark:border-gray-800"
    >
      <h3 className="text-xs font-semibold uppercase tracking-wide text-gray-500">Send to another tool</h3>
      <p className="text-xs text-gray-500 dark:text-gray-400">
        Continue with this result — it stays on your device, no re-uploading.
      </p>
      <div className="grid grid-cols-1 gap-3 sm:grid-cols-2">
        {(Object.keys(SECTION_LABELS) as (keyof CategorizedActions)[]).map((key) =>
          actions[key].length === 0 ? null : (
            <div key={key} className="flex flex-col gap-1">
              <h4 className="text-xs font-medium text-gray-500">{SECTION_LABELS[key]}</h4>
              <ul className="flex flex-col gap-1">
                {actions[key].map((tool) => (
                  <li key={tool.id}>
                    <Link
                      href={getToolUrl(tool)}
                      onClick={() => handOff(tool)}
                      className="text-sm text-blue-600 hover:underline dark:text-blue-400"
                    >
                      {tool.name}
                    </Link>
                  </li>
                ))}
              </ul>
            </div>
          )
        )}
      </div>
    </section>
  );
}
